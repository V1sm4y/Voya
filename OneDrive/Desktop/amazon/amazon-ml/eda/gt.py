import pandas as pd, numpy as np, sys
SP=sys.argv[1] if len(sys.argv)>1 else str(__import__('pathlib').Path(__file__).resolve().parents[1]/'data'/'cache')
gt=pd.read_parquet(f'{SP}/train_ground_truth.parquet')
s1=pd.read_parquet(f'{SP}/train_source1.parquet')
s2ids=set(pd.read_parquet(f'{SP}/train_source2.parquet',columns=['entity_id']).entity_id)
s3ids=set(pd.read_parquet(f'{SP}/train_source3.parquet',columns=['entity_id']).entity_id)
print('gt rows',len(gt),'unique s1',gt.source1_entity_id.nunique(),'s1 in gt == s1 file:',set(gt.source1_entity_id)==set(s1.entity_id))
gt['ids']=gt.matched_entity_ids.map(lambda x:[i for i in x.split(',') if i] if x.strip() else [])
gt['n']=gt.ids.map(len)
gt['n2']=gt.ids.map(lambda l:sum(i.startswith('S2-') for i in l))
gt['n3']=gt.ids.map(lambda l:sum(i.startswith('S3-') for i in l))
print('whitespace in id lists:', gt.matched_entity_ids.str.contains(' ').sum())
print('intra-list duplicates:', (gt.ids.map(len)!=gt.ids.map(lambda l:len(set(l)))).sum())
gt=gt.merge(s1[['entity_id','country']],left_on='source1_entity_id',right_on='entity_id')
print('\nsingletons (no match) pct: %.3f'%((gt.n==0).mean()*100))
print('singleton rate by country:', (gt.n==0).groupby(gt.country).mean().round(4).to_dict())
print('\nmatch-set size distribution:'); vc=gt.n.value_counts().sort_index(); print(pd.DataFrame({'count':vc,'pct':(vc/len(gt)*100).round(3)}).to_string())
print('mean size (all) %.3f, mean size (non-singleton) %.3f'%(gt.n.mean(), gt.n[gt.n>0].mean()))
print('\nby country, size distribution pct:'); print((pd.crosstab(gt.n.clip(upper=8),gt.country,normalize='columns')*100).round(2).to_string())
print('\n(n2,n3) joint distribution pct (clipped at 4):'); print((pd.crosstab(gt.n2.clip(upper=4),gt.n3.clip(upper=4),normalize='all')*100).round(2).to_string())
tot2,tot3=gt.n2.sum(),gt.n3.sum(); print(f'\ntotal matched links: {tot2+tot3:,}  S2 {tot2:,} ({tot2/(tot2+tot3)*100:.1f}%)  S3 {tot3:,} ({tot3/(tot2+tot3)*100:.1f}%)')
print('S1 with >=1 S2 match %.2f%%, >=1 S3 match %.2f%%, both %.2f%%, S2 only %.2f%%, S3 only %.2f%%'%tuple(x*100 for x in [(gt.n2>0).mean(),(gt.n3>0).mean(),((gt.n2>0)&(gt.n3>0)).mean(),((gt.n2>0)&(gt.n3==0)).mean(),((gt.n2==0)&(gt.n3>0)).mean()]))
print('S1 with >=2 from SAME source: S2 %.2f%%  S3 %.2f%%  either %.2f%%  (max n2 %d, max n3 %d)'%((gt.n2>=2).mean()*100,(gt.n3>=2).mean()*100,((gt.n2>=2)|(gt.n3>=2)).mean()*100,gt.n2.max(),gt.n3.max()))
print('n2 distribution:',gt.n2.value_counts().sort_index().to_dict()); print('n3 distribution:',gt.n3.value_counts().sort_index().to_dict())
ex=gt.explode('ids').dropna(subset=['ids'])
c=ex.ids.value_counts()
print(f'\nexploded links {len(ex):,}; unique target ids {ex.ids.nunique():,}; ids in >1 S1 match set: {(c>1).sum():,}; max multiplicity {c.max()}')
if (c>1).sum(): print(ex[ex.ids.isin(c[c>1].index[:5])][['source1_entity_id','ids']])
bad=[i for i in ex.ids if not ((i.startswith('S2-') and i in s2ids) or (i.startswith('S3-') and i in s3ids))]
print('GT ids not found in train S2/S3 files:',len(bad), bad[:5])
used2=ex.ids[ex.ids.str.startswith('S2-')].nunique(); used3=ex.ids[ex.ids.str.startswith('S3-')].nunique()
print(f'S2 records linked to some S1: {used2:,}/{len(s2ids):,} = {used2/len(s2ids)*100:.1f}%  -> unlinked S2 {len(s2ids)-used2:,}')
print(f'S3 records linked to some S1: {used3:,}/{len(s3ids):,} = {used3/len(s3ids)*100:.1f}%  -> unlinked S3 {len(s3ids)-used3:,}')
# country consistency across links
s2=pd.read_parquet(f'{SP}/train_source2.parquet',columns=['entity_id','country']); s3=pd.read_parquet(f'{SP}/train_source3.parquet',columns=['entity_id','country'])
cm=pd.concat([s2,s3]).rename(columns={'entity_id':'ids','country':'tc'})
ex=ex.merge(cm,on='ids'); print('link country agreement S1 vs target: %.5f'%(ex.country==ex.tc).mean())
# upper bound note: order of ids in list
first=gt[gt.n>1].ids.map(lambda l:[i[:2] for i in l])
print('S2 ids listed before S3 ids in every multi list:', first.map(lambda l:l==sorted(l)).mean())
gt[['source1_entity_id','ids','n','n2','n3','country']].to_parquet(f'{SP}/eda_gt_parsed.parquet')
